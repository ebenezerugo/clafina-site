import { z } from 'zod';
import { PageMeta } from './schema';

/** A page address or a title as a URL-safe slug: "/sales/invoices" → "sales-invoices". */
export function slugify(s: string): string {
  return s.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

/**
 * The site does not name payment, messaging or tax-authority services as live (spec section 9). The app's help
 * does, so the sync puts neutral words in their place. Phrases first, then single names.
 */
const NEUTRAL: [RegExp, string][] = [
  [/WhatsApp, Instagram, Telegram and TikTok accounts/g, 'chat and social accounts'],
  [/WhatsApp, Instagram, Telegram, TikTok/g, 'chat and social apps'],
  [/Remita and FIRS/g, 'government payments'],
  [/\bWhatsApp\b/g, 'chat app'],
  [/\b(Instagram|Telegram|TikTok|Messenger)\b/g, 'social app'],
  [/\b(FIRS|Remita)\b/g, 'government payments'],
  // The app's internal name; the public name is Clafina.
  [/\bCommerce\b/g, 'Clafina'],
];
/** Names that must never reach the help centre. The sync fails on one it has no neutral words for. */
export const NAMED_SERVICES = /\b(WhatsApp|Instagram|Telegram|TikTok|Messenger|Facebook|Paystack|Flutterwave|Stripe|Monnify|Opay|OPay|Moniepoint|Remita|FIRS|GRA|KRA|eTIMS|Twilio|Termii|SendGrid|Mailgun)\b/;

export function neutral(s: string): string {
  const out = NEUTRAL.reduce((t, [re, to]) => t.replace(re, to), s);
  const left = out.match(NAMED_SERVICES);
  if (left) throw new Error(`"${left[0]}" has no neutral words in src/content/help.ts: ${s}`);
  return out;
}

const Step = z.strictObject({ lead: z.string(), rest: z.string() });
/** The app's own page help (commerce-web page-help.ts): what the page is for, tasks, words and numbers. */
const PageHelp = z.strictObject({
  purpose: z.string(),
  tasks: z.array(z.strictObject({ label: z.string(), steps: z.array(Step) })).optional(),
  terms: z.array(z.strictObject({ word: z.string(), meaning: z.string(), example: z.string().optional() })).optional(),
  numbers: z.array(z.strictObject({ name: z.string(), how: z.string() })).optional(),
  guide: z.string().optional(),
});

const HelpPage = z.strictObject({
  href: z.string().startsWith('/'),
  anchor: z.string(),
  title: z.string(),
  where: z.string(),
  description: z.string(),
  aliases: z.array(z.string()),
  help: PageHelp.optional(),
});

/** Generated by scripts/sync-help.ts from the app's menu. Never edited by hand. */
export const HelpCatalogue = z.strictObject({
  synced: z.strictObject({ web: z.string(), api: z.string() }),
  sections: z.array(z.strictObject({
    title: z.string(),
    slug: z.string(),
    modules: z.array(z.strictObject({
      title: z.string(),
      slug: z.string(),
      groups: z.array(z.strictObject({ heading: z.string(), pages: z.array(HelpPage).min(1) })).min(1),
    })).min(1),
  })).min(1),
  questions: z.array(z.strictObject({ key: z.string(), title: z.string(), summary: z.string(), path: z.string(), where: z.string(), words: z.array(z.string()) })),
});
export type HelpCatalogue = z.infer<typeof HelpCatalogue>;
export type HelpModuleEntry = HelpCatalogue['sections'][number]['modules'][number];

/** One how-to in a module's guide: a task, done step by step in the app. */
const Article = z.strictObject({
  slug: z.string().regex(/^[a-z0-9-]+$/),
  title: z.string().min(1),
  summary: z.string().min(1).max(200),
  /** Where it is done, as the app's address; must be a page of this module in the catalogue. */
  page: z.string().startsWith('/'),
  before: z.array(z.string()).optional(),
  steps: z.array(Step).min(2).max(12),
  after: z.string().optional(),
  tips: z.array(z.string()).optional(),
  related: z.array(z.string()).optional(),
  prelaunch: z.string().optional(),
});

/** A module's guide, written by hand: what the module is for, how to start, and its how-tos. */
export const HelpModuleGuide = z.strictObject({
  kind: z.literal('help-module'),
  module: z.string(),
  sources: z.array(z.string()).min(1),
  intro: z.string().min(1),
  start: z.array(z.string()).min(1).max(6),
  articles: z.array(Article).min(1),
});
export type HelpModuleGuide = z.infer<typeof HelpModuleGuide>;
export type HelpArticle = HelpModuleGuide['articles'][number];

/** The help centre's own words: its home page. */
export const HelpHome = z.strictObject({
  meta: PageMeta,
  hero: z.strictObject({ eyebrow: z.string(), title: z.string(), lede: z.string(), search: z.string() }),
  startTitle: z.string(),
  moduleStart: z.string(),
  stepsTitle: z.string(),
  beforeTitle: z.string(),
  tipsTitle: z.string(),
  relatedTitle: z.string(),
  start: z.array(z.string()).min(1),
  questionsTitle: z.string(),
  sectionsTitle: z.string(),
  pagesLabel: z.string(),
  articlesLabel: z.string(),
  openInApp: z.string(),
  onThisPage: z.string(),
  everyPage: z.string(),
  howTo: z.string(),
  words: z.string(),
  numbers: z.string(),
  noResults: z.string(),
  stillStuck: z.strictObject({ title: z.string(), body: z.string() }),
});
export type HelpHome = z.infer<typeof HelpHome>;
